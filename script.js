/* =====================================================
   ТАЙМЕР
===================================================== */

function startTimer() {

  clearInterval(timer);

  timer =
    setInterval(() => {

      if (answerLocked)
        return;

      time--;

      timerCircle.textContent =
        time;

      if (time <= 5) {

        timerCircle.style.borderColor =
          "#ff5577";

      }

      if (time <= 0) {

        clearInterval(timer);

        answerLocked = true;

        handleWrongAnswer();

      }

    }, 1000);
}


/* =====================================================
   ПРОВЕРКА ОТВЕТА
===================================================== */

function checkAnswer(
  index,
  selectedButton
) {

  if (answerLocked)
    return;

  answerLocked = true;

  clearInterval(timer);

  const buttons =
    document.querySelectorAll(".answer");

  buttons.forEach(
    button => {
      button.disabled = true;
    }
  );

  if (
    index ===
    currentQuestion.correct
  ) {

    selectedButton.classList.add(
      "correct"
    );

    handleCorrectAnswer();

  } else {

    selectedButton.classList.add(
      "wrong"
    );

    if (
      buttons[
        currentQuestion.correct
      ]
    ) {

      buttons[
        currentQuestion.correct
      ].classList.add(
        "correct"
      );

    }

    handleWrongAnswer();

  }
}


/* =====================================================
   ПРАВИЛЬНО
===================================================== */

function handleCorrectAnswer() {

  streak++;

  const multiplier =
    Math.min(streak, 5);

  const gained =
    100 * multiplier;

  score += gained;

  coins +=
    10 * multiplier;

  saveData();

  showToast(
    "🔥 Правильно! +" +
    gained +
    " очков"
  );

  setTimeout(() => {

    if (isHardLevel()) {

      hardCorrect++;

      hardNextQuestion();

    } else {

      finishNormalLevel(true);

    }

  }, 2000);
}


