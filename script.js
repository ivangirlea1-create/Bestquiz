/* =====================================================
   ВЫБОР КАТЕГОРИИ
===================================================== */

function chooseCategory(cat) {

  selectedCategory = cat;

  const categoryQuestions =
    questionBank.filter(
      q =>
        q.category === cat
    );

  currentQuestions =
    shuffle(categoryQuestions)
      .slice(0, 3);

  /* Если в категории вдруг меньше 3 */

  while (
    currentQuestions.length < 3
  ) {

    const extra =
      questionBank[
        Math.floor(
          Math.random() *
          questionBank.length
        )
      ];

    if (
      !currentQuestions.includes(extra)
    ) {

      currentQuestions.push(extra);

    }

  }

  hardQuestionIndex = 0;
  hardCorrect = 0;

  score = 0;
  streak = 0;
  lives = 3;

  categoryScreen.classList.add(
    "hidden"
  );

  game.classList.remove(
    "hidden"
  );

  hardBadge.classList.remove(
    "hidden"
  );

  currentQuestion =
    currentQuestions[0];

  showHardQuestion();
}


